export const I18N_DICTIONARY: Record<SupportedLocale, PartialUiDict> = {
  en: EN_UI,
  es: ES_UI,
  fr: FR_UI,
  de: DE_UI,
  ja: JA_UI,
  pt: PT_UI
};

export function translateUi(
  locale: SupportedLocale,
  key: UiTranslationKey,
  vars?: Record<string, string | number>
): string {
  const dict = I18N_DICTIONARY[locale] || EN_UI;
  let text = dict[key] ?? EN_UI[key] ?? key;
  if (vars) {
    for (const [varKey, varVal] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${varKey}\\}`, 'g'), String(varVal));
    }
  }
  return text;
}
