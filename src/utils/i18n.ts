export const VALID_LOCALES = new Set<SupportedLocale>(['en', 'es', 'fr', 'de', 'ja', 'pt']);

export const LANGUAGE_SWITCHER_CODES: readonly SupportedLocale[] = ['en', 'es', 'fr', 'ja'];

export function isSupportedLocale(val?: string | null): val is SupportedLocale {
  return Boolean(val && VALID_LOCALES.has(val as SupportedLocale));
}

export function getLocaleConfig(locale: SupportedLocale): LocaleConfig {
  return LOCALE_CONFIGS.find((c) => c.code === locale) || LOCALE_CONFIGS[0];
}

export function getLanguageSwitcherLocales(): LocaleConfig[] {
  return LANGUAGE_SWITCHER_CODES.map((code) => getLocaleConfig(code));
}

export function getNextLanguageLocale(current: SupportedLocale): SupportedLocale {
  const idx = LANGUAGE_SWITCHER_CODES.indexOf(current);
  if (idx === -1) return LANGUAGE_SWITCHER_CODES[0];
  return LANGUAGE_SWITCHER_CODES[(idx + 1) % LANGUAGE_SWITCHER_CODES.length];
}

export function resolveInitialLocale(
  savedLocale?: string | null,
  _browserLanguage?: string | null
): SupportedLocale {
  if (isSupportedLocale(savedLocale)) {
    return savedLocale;
  }
  return 'en';
}

